import react from '@vitejs/plugin-react'
import { defineConfig, type Plugin } from 'vite'
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'

/**
 * Generates dist/sw.js after every build.
 * It precaches the whole app (HTML, JS, CSS, fonts, images) so the app opens
 * with NO internet after the first visit, and keeps map tiles you have viewed.
 */
function offlineServiceWorker(): Plugin {
  let outDir = 'dist'
  const walk = (dir: string): string[] =>
    readdirSync(dir).flatMap((name) => {
      const p = join(dir, name)
      return statSync(p).isDirectory() ? walk(p) : [p]
    })

  return {
    name: 'offline-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir)
    },
    closeBundle() {
      const files = walk(outDir)
        .map((f) => relative(outDir, f).split('\\').join('/'))
        .filter((f) => f !== 'sw.js')
      const hash = createHash('sha1')
      files.forEach((f) => hash.update(f + readFileSync(join(outDir, f)).length))
      const version = hash.digest('hex').slice(0, 10)

      const sw = `/* Auto-generated by vite.config.ts — do not edit */
const VERSION = 'matru-netra-${version}';
const TILE_CACHE = 'matru-netra-map-tiles';
const PRECACHE = ${JSON.stringify(['./', ...files])};
const TILE_HOSTS = ['tile.openstreetmap.org', 'server.arcgisonline.com'];
const MAX_TILES = 800;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(VERSION)
      .then((cache) => cache.addAll(PRECACHE.map((p) => new URL(p, self.registration.scope).href)))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION && k !== TILE_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

async function trimTiles(cache) {
  const keys = await cache.keys();
  if (keys.length > MAX_TILES) {
    await Promise.all(keys.slice(0, keys.length - MAX_TILES).map((k) => cache.delete(k)));
  }
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // Map tiles: use saved copy if we have it, otherwise fetch and save it
  if (TILE_HOSTS.includes(url.hostname)) {
    event.respondWith(
      caches.open(TILE_CACHE).then(async (cache) => {
        const hit = await cache.match(req);
        if (hit) return hit;
        try {
          const res = await fetch(req);
          if (res.ok || res.type === 'opaque') { cache.put(req, res.clone()); trimTiles(cache); }
          return res;
        } catch (e) {
          return Response.error();
        }
      })
    );
    return;
  }

  // Everything else from other websites (e.g. database calls): leave alone
  if (url.origin !== self.location.origin) return;

  // Opening the app: try the network briefly, otherwise use the saved copy
  if (req.mode === 'navigate') {
    event.respondWith(
      new Promise((resolve) => {
        const timer = setTimeout(async () => resolve((await caches.match(new URL('./', self.registration.scope).href)) || Response.error()), 3500);
        fetch(req).then((res) => { clearTimeout(timer); resolve(res); })
          .catch(async () => { clearTimeout(timer); resolve((await caches.match(new URL('./', self.registration.scope).href)) || Response.error()); });
      })
    );
    return;
  }

  // App files (JS, CSS, fonts, images): saved copy first
  event.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }
      return res;
    }))
  );
});
`
      writeFileSync(join(outDir, 'sw.js'), sw)
    },
  }
}

// https://vite.dev/config/
export default defineConfig({
  base: './',
  plugins: [react(), offlineServiceWorker()],
})
